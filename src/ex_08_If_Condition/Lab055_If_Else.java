package ex_08_If_Condition;

public class Lab055_If_Else {

    public static void main(String[] args) {
        int a = 10;

        if (a == 5)
        {
            System.out.println("The value of a is equal to 5");
        }
        else
        {
            System.out.println("The value of a is not equal to 5");
        }
    }
}
