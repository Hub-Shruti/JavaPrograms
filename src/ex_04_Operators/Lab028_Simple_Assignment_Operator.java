package ex_04_Operators;

import java.util.Scanner;

public class Lab028_Simple_Assignment_Operator {

    public static void main(String[] args) {

        int age = 90;
        // int -> data type
        // age -> identifier
        // 90 -> Literal
        // = -> Assignment operator

        // RHV to the LH

        System.out.println(age);

        char a1 = 'A';     // ASCII -> 65
        char b1 = 'B';     // ASCII -> 66
        System.out.println(a1 + b1);    // a1+b1 -> 65+66 -> Output is 131

    }

}
