package ex_04_Operators;

public class Lab034_Compound_Assignment_Operators {

    public static void main(String[] args) {

        // COMPOUND ASSIGNMENT OPERATORS //
        // +=
        // -=
        // /=
        // *=

        int age = 10;
        age += 10;
        System.out.println(age);     // age = age+10 ---> Output is 20
        age -=10;
        System.out.println(age);     // age = age-10 ---> Output is 10
        age /=10;
        System.out.println(age);     // age = age/10 ---> Output is 1
        age *=10;
        System.out.println(age);     // age = age*10 ---> Output is 10

    }
}
