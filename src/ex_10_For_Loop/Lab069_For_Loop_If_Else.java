package ex_10_For_Loop;

public class Lab069_For_Loop_If_Else {

    public static void main(String[] args) {

        for (int Sita = 0; Sita < 18; Sita ++)       // 0 to 17 -> 18 times
        {
            if (Sita > 15)
            {
                System.out.println("Gift");
            }
            else
            {
                System.out.println("No Gift");
            }
        }
    }
}
